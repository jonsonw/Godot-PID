def _run():
    nominal_sizes = _read_nominal()
    print("Nominal sizes: %s" % nominal_sizes)

    if not os.path.isdir(PACKS_DIR):
        print("[error] %s not found" % PACKS_DIR, file=sys.stderr)
        sys.exit(1)

    pack_ids = sorted(d for d in os.listdir(PACKS_DIR)
                      if os.path.isdir(os.path.join(PACKS_DIR, d)))
    print("Discovered packs: %s" % pack_ids)

    all_meta = []
    all_entries_by_pack = {}
    for pack_id in pack_ids:
        pack_dir = os.path.join(PACKS_DIR, pack_id)
        meta, entries, out_path = _process_pack(pack_dir, pack_id, nominal_sizes)
        if meta:
            all_meta.append(meta)
            all_entries_by_pack[pack_id] = entries
            print("-> %s (%d defs)" % (out_path, len(entries)))

    # Write pack registry summary (for reference / 供参考)。
    reg_path = os.path.join(OUT_DIR, "_pack_registry.json")
    with open(reg_path, "w", encoding="utf-8") as f:
        json.dump(all_meta, f, ensure_ascii=False, indent=2)
    print("\nWrote pack registry to %s" % reg_path)
    print("Total packs: %d" % len(all_meta))


if __name__ == "__main__":
    _run()
